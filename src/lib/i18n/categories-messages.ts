export const categoriesMessagesByLocale = byLocale({ es, en, pt });

/** El texto de un `code` de la API o de la validación, en Categorías. */
export function categoriesErrorText(code: string, locale: Locale = "es"): string {
  const errors = categoriesMessagesByLocale[locale].errors;
  return errors[code] ?? errors.unknown ?? "";
}
