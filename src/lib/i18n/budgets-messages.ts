export const budgetsMessagesByLocale = byLocale({ es, en, pt });

export function budgetErrorText(code: string, locale: Locale = "es"): string {
  const errors = budgetsMessagesByLocale[locale].errors;
  return errors[code] ?? errors.unknown ?? "";
}
