export const recurringMessagesByLocale = byLocale({ es, en, pt });

export function recurringErrorText(code: string, locale: Locale = "es"): string {
  const errors = recurringMessagesByLocale[locale].errors;
  return errors[code] ?? errors.unknown ?? "";
}
