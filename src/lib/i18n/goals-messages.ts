export const goalsMessagesByLocale = byLocale({ es, en, pt });

export function goalErrorText(code: string, locale: Locale = "es"): string {
  const errors = goalsMessagesByLocale[locale].errors;
  return errors[code] ?? errors.unknown ?? "";
}
