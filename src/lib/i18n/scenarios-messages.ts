export const scenariosMessagesByLocale = byLocale({ es, en, pt });

export function scenarioErrorText(code: string, locale: Locale = "es"): string {
  const errors = scenariosMessagesByLocale[locale].errors;
  return errors[code] ?? errors.unknown ?? "";
}
