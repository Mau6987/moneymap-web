export const registerMessagesByLocale = byLocale({ es, en, pt });

export function registerErrorText(code: string, locale: Locale = "es"): string {
  const errors = registerMessagesByLocale[locale].errors;
  return errors[code] ?? errors.unknown ?? "";
}
